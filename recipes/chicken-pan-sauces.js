function chickenIngredients(portion,cookMode){
  const p = portionInfo[portion];
  const base = [
    ["🍗 Куриная грудка", p.chickenWeight],
    ["🧂 Соль", p.salt],
    ["⚫ Чёрный перец", "по вкусу"],
    ["🌻 Нейтральное масло", p.oil]
  ];
  if(cookMode === "basting"){
    base.push(
      ["🧈 Сливочное масло для basting", p.bastingButter],
      ["🧄 Чеснок", p.garlic],
      ["🌿 Тимьян", p.thyme]
    );
  }
  return base;
}

